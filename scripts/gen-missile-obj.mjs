// Writes public/obj/missile.obj, the guided missile upstream models at
// `useQuality() >= 3` (renderGeoGMBolt, BoltSceneNode.cxx:326): its
// `gluCylinder`/`gluDisk` stack and four fins, at a `_gmSize` of one, nose
// along +Z and the tail near the origin, where the shot itself is.
//
// One object per colour upstream paints -- `nose` (the shot's colour), `fin`
// (half of it), `body` (white) and `cone` (dark grey) -- so the renderer can
// colour a missile by its shooter without the file knowing any colours.
//
//   node scripts/gen-missile-obj.mjs

import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { writeFileSync } from 'fs';

const __dirname = dirname(fileURLToPath(import.meta.url));

// renderGeoGMBolt's parametrics, as fractions of `gmMissleSize`.
const maxRad = 0.16;
const noseRad = 0.086;
const waistRad = 0.125;
const engineRad = 0.1;
const noseLen = 0.1;
const bodyLen = 0.44;
const bevelLen = 0.02;
const waistLen = 0.16;
const boosterLen = 0.2;
const engineLen = 0.08;
const finRadius = 0.16;
const finCapSize = 0.15;
const finForeDelta = 0.02;
const slices = 8;

const parts = new Map([['nose', []], ['body', []], ['cone', []], ['fin', []]]);
const tri = (part, a, b, c) => parts.get(part).push([a, b, c]);

const ring = (radius, z, k) => {
  const angle = (k / slices) * Math.PI * 2;
  return [Math.cos(angle) * radius, Math.sin(angle) * radius, z];
};

// `gluCylinder(base, top, height)` from `z`: `base` at `z`, `top` at
// `z + height`, wound outward.
const cylinder = (part, z, base, top, height) => {
  for (let k = 0; k < slices; k += 1) {
    const a0 = ring(base, z, k);
    const a1 = ring(base, z, k + 1);
    const b0 = ring(top, z + height, k);
    const b1 = ring(top, z + height, k + 1);
    tri(part, a0, a1, b1);
    tri(part, a0, b1, b0);
  }
};

// The same walk upstream makes: out to the nose, then back down the body one
// translation at a time, the colour changing where upstream's does.
let z = 1;
for (let k = 0; k < slices; k += 1) tri('nose', [0, 0, z], ring(noseRad, z, k), ring(noseRad, z, k + 1));
z -= noseLen;
cylinder('nose', z, maxRad, noseRad, noseLen);
z -= bodyLen;
cylinder('body', z, maxRad, maxRad, bodyLen);
z -= bevelLen;
cylinder('body', z, waistRad, maxRad, bevelLen);
z -= waistLen;
cylinder('cone', z, waistRad, waistRad, waistLen);
z -= bevelLen;
cylinder('body', z, maxRad, waistRad, bevelLen);
z -= boosterLen;
const finBase = z;
cylinder('body', z, maxRad, maxRad, boosterLen);
z -= bevelLen;
cylinder('body', z, waistRad, maxRad, bevelLen);
z -= engineLen;
cylinder('cone', z, engineRad, waistRad, engineLen);

// drawFin, at the four quarter turns: a strip in the plane of the turn, from
// the booster's skin out to the fin's tip. One-sided here; the renderer draws
// the missile two-sided, as upstream draws each fin twice.
for (let i = 0; i < 4; i += 1) {
  const angle = i * (Math.PI / 2);
  const at = (radius, along) => [-Math.sin(angle) * radius, Math.cos(angle) * radius, finBase + along];
  const p0 = at(maxRad, 0);
  const p1 = at(maxRad, boosterLen);
  const p2 = at(maxRad + finRadius, boosterLen - finForeDelta - finCapSize);
  const p3 = at(maxRad + finRadius, boosterLen - finForeDelta);
  tri('fin', p0, p1, p2);
  tri('fin', p2, p1, p3);
}

const lines = [
  '# Guided missile for BZO, upstream renderGeoGMBolt at _gmSize 1',
  '# Generated by scripts/gen-missile-obj.mjs',
  '# Nose along +Z; objects are the colours upstream paints: nose, fin, body, cone.',
];
let vertexCount = 0;
const round = (n) => Number(n.toFixed(5));
for (const [name, triangles] of parts) {
  lines.push(`o ${name}`);
  for (const triangle of triangles) {
    for (const [x, y, zz] of triangle) lines.push(`v ${round(x)} ${round(y)} ${round(zz)}`);
  }
  for (let i = 0; i < triangles.length; i += 1) {
    const base = vertexCount + (i * 3);
    lines.push(`f ${base + 1} ${base + 2} ${base + 3}`);
  }
  vertexCount += triangles.length * 3;
}

const outPath = resolve(__dirname, '../public/obj/missile.obj');
writeFileSync(outPath, `${lines.join('\n')}\n`);
console.log(`Written: ${outPath}`);
console.log(`Triangles: ${vertexCount / 3}`);
